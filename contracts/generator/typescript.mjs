// Writes the TypeScript declarations of an OpenAPI document: node typescript.mjs <openapi.json> <output.ts>
// Called by apps/api/contract/generate.ts; openapi-typescript resolves TypeScript 5 from this package.
import { readFileSync, writeFileSync } from 'node:fs';

import openapiTS, { astToString } from 'openapi-typescript';

const [input, output] = process.argv.slice(2);
if (input === undefined || output === undefined) {
  throw new Error('Usage: node typescript.mjs <openapi.json> <output.ts>');
}
const ast = await openapiTS(JSON.parse(readFileSync(input, 'utf8')));
const banner = '// Generated by openapi-typescript 7.13.0 from the OpenAPI document. Do not edit: run `bun run contract:generate`.\n\n';
writeFileSync(output, banner + astToString(ast));
